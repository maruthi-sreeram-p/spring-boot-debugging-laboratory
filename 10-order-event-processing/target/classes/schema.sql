-- Riverstone order pipeline schema (PostgreSQL 16)
-- Applied on every boot; every statement is idempotent.

CREATE TABLE IF NOT EXISTS stock_items (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku       VARCHAR(32)  NOT NULL UNIQUE,
    name      VARCHAR(160) NOT NULL,
    available INT          NOT NULL DEFAULT 0,
    reserved  INT          NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_ref    VARCHAR(32) NOT NULL UNIQUE,
    customer_ref VARCHAR(64) NOT NULL,
    sku          VARCHAR(32) NOT NULL,
    quantity     INT         NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);

CREATE TABLE IF NOT EXISTS reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_ref  VARCHAR(32) NOT NULL,
    sku        VARCHAR(32) NOT NULL,
    quantity   INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reservations_order ON reservations (order_ref);

CREATE TABLE IF NOT EXISTS order_notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_ref  VARCHAR(32)  NOT NULL,
    channel    VARCHAR(16)  NOT NULL,
    subject    VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_order_notifications_order ON order_notifications (order_ref);

CREATE TABLE IF NOT EXISTS event_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic          VARCHAR(64)  NOT NULL,
    partition_no   INT          NOT NULL,
    offset_no      BIGINT       NOT NULL,
    message_key    VARCHAR(64),
    event_type     VARCHAR(40)  NOT NULL,
    order_ref      VARCHAR(32)  NOT NULL,
    consumer_group VARCHAR(64)  NOT NULL,
    handled_by     VARCHAR(64)  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_event_log_order ON event_log (order_ref);
CREATE INDEX IF NOT EXISTS idx_event_log_topic ON event_log (topic, partition_no);

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role_name     VARCHAR(40)  NOT NULL
);

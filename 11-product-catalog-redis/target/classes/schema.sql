-- Lumen Retail catalogue schema (PostgreSQL 16)
-- Applied on every boot; every statement is idempotent.

CREATE TABLE IF NOT EXISTS categories (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug     VARCHAR(80)  NOT NULL UNIQUE,
    name     VARCHAR(120) NOT NULL,
    position INT          NOT NULL DEFAULT 0,
    active   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(40)    NOT NULL UNIQUE,
    name        VARCHAR(180)   NOT NULL,
    description VARCHAR(1200),
    brand       VARCHAR(80)    NOT NULL,
    category_id BIGINT         NOT NULL REFERENCES categories (id),
    price       NUMERIC(12, 2) NOT NULL,
    currency    CHAR(3)        NOT NULL DEFAULT 'INR',
    active      BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ    NOT NULL,
    updated_at  TIMESTAMPTZ    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_products_category ON products (category_id);
CREATE INDEX IF NOT EXISTS idx_products_brand ON products (brand);

CREATE TABLE IF NOT EXISTS product_variants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT         NOT NULL REFERENCES products (id),
    variant_sku VARCHAR(48)    NOT NULL UNIQUE,
    label       VARCHAR(80)    NOT NULL,
    price_delta NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    active      BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_variants_product ON product_variants (product_id);

CREATE TABLE IF NOT EXISTS price_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT         NOT NULL REFERENCES products (id),
    old_price  NUMERIC(12, 2) NOT NULL,
    new_price  NUMERIC(12, 2) NOT NULL,
    changed_by VARCHAR(120)   NOT NULL,
    changed_at TIMESTAMPTZ    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_price_history_product ON price_history (product_id, changed_at DESC);

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role_name     VARCHAR(40)  NOT NULL
);

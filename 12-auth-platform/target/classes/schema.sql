-- Aegis identity platform schema (PostgreSQL 16)
-- Applied on every boot; every statement is idempotent.

CREATE TABLE IF NOT EXISTS accounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            VARCHAR(190) NOT NULL UNIQUE,
    password_hash    VARCHAR(100) NOT NULL,
    display_name     VARCHAR(120) NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    failed_attempts  INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_login_at    TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60)  NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS account_roles (
    account_id BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    role_id    BIGINT NOT NULL REFERENCES roles (id)    ON DELETE CASCADE,
    PRIMARY KEY (account_id, role_id)
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles (id)       ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT       NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    token_id    VARCHAR(64)  NOT NULL UNIQUE,
    token_hash  VARCHAR(90)  NOT NULL,
    issued_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked     BOOLEAN      NOT NULL DEFAULT FALSE,
    replaced_by VARCHAR(64),
    user_agent  VARCHAR(200)
);

CREATE INDEX IF NOT EXISTS idx_refresh_account ON refresh_tokens (account_id);

CREATE TABLE IF NOT EXISTS documents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference   VARCHAR(40)  NOT NULL UNIQUE,
    title       VARCHAR(200) NOT NULL,
    body        TEXT         NOT NULL,
    owner_id    BIGINT       NOT NULL REFERENCES accounts (id),
    sensitivity VARCHAR(20)  NOT NULL DEFAULT 'INTERNAL',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT,
    event_type VARCHAR(40)  NOT NULL,
    detail     VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_events (created_at DESC);

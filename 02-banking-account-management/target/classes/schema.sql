-- Meridian Bank core ledger schema (PostgreSQL 16)
-- Applied on every boot; every statement is idempotent.

CREATE TABLE IF NOT EXISTS roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS customers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    national_id   VARCHAR(40)  NOT NULL UNIQUE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL
);

CREATE TABLE IF NOT EXISTS customer_roles (
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    role_id     BIGINT NOT NULL REFERENCES roles (id),
    PRIMARY KEY (customer_id, role_id)
);

CREATE TABLE IF NOT EXISTS accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(24)    NOT NULL UNIQUE,
    customer_id    BIGINT         NOT NULL REFERENCES customers (id),
    account_type   VARCHAR(20)    NOT NULL,
    currency       CHAR(3)        NOT NULL,
    balance        NUMERIC(18, 2) NOT NULL DEFAULT 0.00,
    status         VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',
    opened_at      TIMESTAMPTZ    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_accounts_customer ON accounts (customer_id);

CREATE TABLE IF NOT EXISTS transactions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference               VARCHAR(32)    NOT NULL UNIQUE,
    account_id              BIGINT         NOT NULL REFERENCES accounts (id),
    counterparty_account_id BIGINT         REFERENCES accounts (id),
    tx_type                 VARCHAR(20)    NOT NULL,
    amount                  NUMERIC(18, 2) NOT NULL,
    balance_after           NUMERIC(18, 2) NOT NULL,
    description             VARCHAR(200),
    created_at              TIMESTAMPTZ    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_transactions_account_created ON transactions (account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_type ON transactions (tx_type);
